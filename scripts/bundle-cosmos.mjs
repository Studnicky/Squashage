/**
 * bundle-cosmos.mjs — produce the vendored cosmos.gl/graph bundle.
 *
 * Run via: node scripts/bundle-cosmos.mjs
 * Outputs: src/viz/vendor/cosmosBundle.ts (a TS module that exports the
 * minified JS as a string constant, mirroring the sigma-bundle pattern.
 * The string is embedded inline in the demo HTML wrapper.)
 */
import { build } from 'esbuild';
import { writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT     = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = resolve(ROOT, 'src/viz/vendor/cosmosBundle.ts');

const result = await build({
  stdin: {
    contents: "import { Graph } from '@cosmos.gl/graph'; window.CosmosGraph = Graph;",
    resolveDir: ROOT,
    loader: 'js',
  },
  bundle: true,
  format: 'iife',
  minify: true,
  write: false,
  target: ['es2020'],
  // cosmos.gl uses WebGL — needs browser-like env
  platform: 'browser',
});

const js     = new TextDecoder().decode(result.outputFiles[0].contents);
const sizeKB = (js.length / 1024).toFixed(1);

const tsSource =
  '/**\n' +
  ' * cosmosBundle.ts — vendored cosmos.gl/graph bundle. Generated by scripts/bundle-cosmos.mjs. Do not edit by hand.\n' +
  ' *\n' +
  ' * Combined size: ' + sizeKB + ' KB minified.\n' +
  ' */\n' +
  '\n' +
  'export const COSMOS_BUNDLE = ' + JSON.stringify(js) + ';\n';

await mkdir(resolve(ROOT, 'src/viz/vendor'), { recursive: true });
await writeFile(OUT_PATH, tsSource, 'utf-8');
console.log('cosmos bundle: ' + OUT_PATH + ' (' + sizeKB + ' KB)');
