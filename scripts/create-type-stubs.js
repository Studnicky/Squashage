#!/usr/bin/env node
/**
 * Creates local @types stubs for OSS packages that ship no TypeScript
 * declarations and have no community @types package for their current major
 * version.  Run automatically via the `postinstall` npm script.
 *
 * Packages covered:
 *   n3 v2.x          — no upstream @types/n3 covers v2
 *   jsonld v9.x      — no upstream @types/jsonld covers v9
 *   rdf-canonize v5  — no @types/rdf-canonize package exists
 *
 * Remove an entry here when the package ships its own types or when v1.x
 * swaps to @semantics/rdf-canonicalize (which ships its own declarations).
 *
 * @since 2.2.0
 */

import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TYPES_DIR = join(ROOT, 'node_modules', '@types');

/**
 * Write a local @types stub unless a real (non-local) types package is already
 * installed.
 */
function writeStub(pkgName, pkgJson, indexDts) {
  const dir = join(TYPES_DIR, pkgName);
  const pkgJsonPath = join(dir, 'package.json');
  if (existsSync(pkgJsonPath)) {
    let existing;
    try {
      existing = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
    } catch {
      // Ignore parse errors — overwrite the stub
    }
    if (existing && !existing.description?.includes('Local type stub')) {
      process.stdout.write(`[type-stubs] @types/${pkgName} — real types installed, skipping\n`);
      return;
    }
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(pkgJsonPath, JSON.stringify(pkgJson, null, 2) + '\n');
  writeFileSync(join(dir, 'index.d.ts'), indexDts);
  process.stdout.write(`[type-stubs] Created @types/${pkgName}\n`);
}

// ── n3 v2.x ─────────────────────────────────────────────────────────────────

writeStub('n3', {
  name: '@types/n3',
  version: '0.0.1-local',
  description: 'Local type stub for n3 v2.x (no upstream @types/n3 for v2 exists).',
  types: 'index.d.ts',
  license: 'MIT',
}, `/**
 * Local type stub for n3 v2.x — generated by scripts/create-type-stubs.js.
 * Remove when upstream ships types or when v1.x swaps to @semantics/rdf-io.
 * @since 2.2.0
 */
import type { Quad } from '@rdfjs/types';

export type Prefixes = Record<string, string>;

export type ParseCallback = (
  error:    Error | null,
  quad:     Quad  | null,
  prefixes: Prefixes | undefined,
) => void;

export interface ParserOptions {
  format?:          string;
  baseIRI?:         string;
  blankNodePrefix?: string;
}

export class Parser {
  constructor(options?: ParserOptions);
  parse(input: string, callback: ParseCallback): void;
  parse(input: string): Quad[];
}
`);

// ── rdf-canonize v5.x ───────────────────────────────────────────────────────

writeStub('rdf-canonize', {
  name: '@types/rdf-canonize',
  version: '0.0.1-local',
  description: 'Local type stub for rdf-canonize v5.x (no @types/rdf-canonize exists on npm).',
  types: 'index.d.ts',
  license: 'MIT',
}, `/**
 * Local type stub for rdf-canonize v5.x — generated by scripts/create-type-stubs.js.
 * Remove when upstream ships types or when v1.x swaps to @semantics/rdf-canonicalize.
 * @since 2.2.0
 */
import type { Quad } from '@rdfjs/types';

export interface CanonizeOptions {
  /** Canonicalization algorithm. Use 'RDFC-1.0' (the W3C-standardized algorithm). */
  algorithm: 'RDFC-1.0' | 'URDNA2015';
}

/**
 * Asynchronously canonizes an RDF dataset using the RDFC-1.0 algorithm.
 *
 * @param input   - Iterable of RDF/JS-compatible quad objects.
 * @param options - Must include \`algorithm: 'RDFC-1.0'\`.
 * @returns A Promise resolving to a canonical N-Quads string (sorted,
 *          with stable blank-node c14nN identifiers).
 */
export declare function canonize(
  input:   Iterable<Quad>,
  options: CanonizeOptions,
): Promise<string>;
`);

// ── jsonld v9.x ─────────────────────────────────────────────────────────────

writeStub('jsonld', {
  name: '@types/jsonld',
  version: '0.0.1-local',
  description: 'Local type stub for jsonld v9.x (no upstream @types/jsonld for v9 exists).',
  types: 'index.d.ts',
  license: 'MIT',
}, `/**
 * Local type stub for jsonld v9.x — generated by scripts/create-type-stubs.js.
 * Remove when upstream ships types or when v1.x swaps to @semantics/rdf-io.
 * @since 2.2.0
 */

export interface ToRdfOptions {
  format?: string;
  base?:   string;
}

export interface ExpandOptions {
  base?:             string;
  expandContext?:    unknown;
  keepFreeFloatingNodes?: boolean;
}

export interface JsonLdApi {
  toRDF(input: unknown, options?: ToRdfOptions): Promise<string>;
  expand(input: unknown, options?: ExpandOptions): Promise<unknown[]>;
}

declare const jsonld: JsonLdApi;
export default jsonld;
`);
