/**
 * bundle-sigma.mjs — produce the vendored sigma+graphology bundle.
 *
 * Run via: node scripts/bundle-sigma.mjs
 * Outputs: src/viz/vendor/sigmaBundle.ts (a TS module that exports the
 * minified JS as a string constant, mirroring the cytoscape-bundle pattern.
 * The string is embedded inline in the demo HTML wrapper.)
 */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT     = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = resolve(ROOT, 'src/viz/vendor/sigmaBundle.ts');

const result = await build({
  stdin: {
    contents:
      "import Graph from 'graphology';" +
      "import Sigma from 'sigma';" +
      "window.Graphology = Graph;" +
      "window.Sigma = Sigma;",
    resolveDir: ROOT,
    loader: 'js',
  },
  bundle: true,
  format: 'iife',
  minify: true,
  write:  false,
  target: ['es2020'],
});

const js     = new TextDecoder().decode(result.outputFiles[0].contents);
const sizeKB = (js.length / 1024).toFixed(1);

const tsSource =
  '/**\n' +
  ' * sigmaBundle.ts — vendored sigma + graphology bundle.\n' +
  ' *\n' +
  ' * Generated by scripts/bundle-sigma.mjs. Do not edit by hand.\n' +
  ' * Combined size: ' + sizeKB + ' KB minified.\n' +
  ' */\n' +
  '\n' +
  'export const SIGMA_BUNDLE = ' + JSON.stringify(js) + ';\n';

await writeFile(OUT_PATH, tsSource, 'utf-8');
console.log('sigma bundle: ' + OUT_PATH + ' (' + sizeKB + ' KB)');
